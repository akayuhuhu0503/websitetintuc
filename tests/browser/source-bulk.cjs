const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
 const run=process.argv[2], {url}=JSON.parse(fs.readFileSync(run+'/ready.json','utf8'));
 assert.match(url,/^http:\/\/127\.0\.0\.1:\d+$/);
 const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
 const context=await browser.newContext({extraHTTPHeaders:{'X-Fixture-Actor':'admin'},viewport:{width:1366,height:900}});
 const page=await context.newPage(),errors=[],checks=[];page.on('pageerror',e=>errors.push(e.message));
 const check=(ok,label)=>{assert.ok(ok,label);checks.push(label);};
 await page.goto(url+'/admin/source-sync');
 await page.locator('#source-bulk-page').check();
 const first=await page.locator('.source-bulk-row:checked').count();check(first===20,'Select 20 eligible rows on page');
 await page.getByRole('link',{name:'Trang sau',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.pagination')?.textContent.includes('Trang 2'));
 await page.locator('#source-bulk-page').check();
 const second=await page.locator('.source-bulk-row:checked').count();
 check((await page.locator('#source-bulk-count').textContent()).includes(String(first+second)),'Selection retained across pages');
 await page.reload();check((await page.locator('#source-bulk-count').textContent()).includes(String(first+second)),'Selection restored after reload');
 await page.locator('#sync-filter [name=q]').fill('Bulk fixture 9200');await page.getByRole('button',{name:'Lọc',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#source-bulk-count')?.textContent.includes('Đã chọn 0'));
 check(await page.locator('.source-bulk-row:checked').count()===0,'Filter change clears prior scope');
 await page.locator('.source-bulk-row').nth(0).check();await page.locator('.source-bulk-row').nth(1).check();
 const chosen=await page.locator('.source-bulk-row:checked').evaluateAll(rows=>rows.map(x=>x.dataset.id));
 await page.locator('[data-source-bulk-action="Draft"]').click();await page.locator('#source-bulk-dialog').waitFor({state:'visible'});
 check((await page.locator('#source-bulk-summary').textContent()).includes('Đủ điều kiện 2'),'Preview includes eligible count');
 await page.locator('#source-bulk-confirm').click();
 await page.waitForFunction(()=>document.querySelector('#source-bulk-confirm').hidden,{timeout:60000});
 check((await page.locator('#source-bulk-summary').textContent()).includes('Chuyển nháp 2'),'Draft batch uses real HTTP workflow');
 check(await page.locator('#source-bulk-results a[href^="/admin/edit/"]').count()===2,'Draft results have editor links');
 await page.locator('#source-bulk-close').click();
 await page.waitForFunction(()=>document.querySelector('#source-bulk-count').textContent.includes('Đã chọn 0'));
 await page.waitForFunction(ids=>ids.every(id=>!document.querySelector('.source-bulk-row[data-id="'+id+'"]')),chosen);
 await page.locator('.source-bulk-row').first().check();await page.locator('[data-source-bulk-action="Ignore"]').click();await page.locator('#source-bulk-confirm').click();
 await page.waitForFunction(()=>document.querySelector('#source-bulk-confirm').hidden,{timeout:60000});
 check((await page.locator('#source-bulk-summary').textContent()).includes('Bỏ qua 1'),'Ignore batch completes independently');
 await page.locator('#source-bulk-close').click();await page.setViewportSize({width:390,height:844});
 await page.locator('.source-bulk-row').first().check();await page.locator('[data-source-bulk-action="Draft"]').click();
 await page.locator('#source-bulk-dialog').waitFor({state:'visible'});
 const bounds=await page.locator('#source-bulk-dialog').boundingBox();check(bounds.x>=0&&bounds.x+bounds.width<=391,'Mobile confirmation stays within viewport');
 check(errors.length===0,'No browser JavaScript errors');
 fs.writeFileSync(run+'/browser-result.json',JSON.stringify({passed:checks.length,checks,errors},null,2));
 await browser.close();fs.writeFileSync(run+'/browser.done','done');console.log(JSON.stringify({passed:checks.length,checks}));
})().catch(e=>{console.error(e);process.exit(1);});
